    # -- L2 errors / issues ----------------------------------------------

    def _errors(self) -> Dict[str, Any]:
        s = self.state
        critical = []
        warning = []
        info = []
        if s["cache_hit"] < 95:
            warning.append("LSCache 命中率低于 95%，存在可缓存请求未命中")
        if self._php()["avg_time"] > 120:
            warning.append("PHP 平均执行时间偏高，疑似慢插件或慢查询")
        if self._worker()["queue"] > 200:
            critical.append("Worker 连接池排队严重，请求出现排队等待")
        if self._database()["slow_queries"] > 40:
            warning.append("数据库慢查询数量偏多，建议添加索引")
        if self._redis()["hit"] < 90:
            info.append("Redis 命中率一般，可增大内存上限或调整 TTL")
        warning.append("admin-ajax.php 占用大量 worker，建议限制心跳频率")
        info.append("wp_options 表 autoload 数据较大，建议清理")
        return {
            "critical": [{"level": "critical", "text": t} for t in critical],
            "warning": [{"level": "warning", "text": t} for t in warning],
            "info": [{"level": "info", "text": t} for t in info],
        }

    # -- L3 AI analysis ---------------------------------------------------

    def _ai_analysis(self, score: Dict[str, Any]) -> Dict[str, Any]:
        items = []
        comps = score["components"]
        for key, c in comps.items():
            if c["score"] >= 90:
                status = "健康"
                cause = "指标处于优秀区间，无需干预。"
                suggestion = "保持当前配置即可。"
            elif c["score"] >= 80:
                status = "良好"
                cause = "存在轻微波动，不影响整体体验。"
                suggestion = "可在低峰期微调参数。"
            elif c["score"] >= 70:
                status = "需关注"
                cause = "部分请求超出预期延迟，存在隐患。"
                suggestion = "建议执行对应优化项。"
            else:
                status = "异常"
                cause = "关键指标劣化明显，已影响用户体验。"
                suggestion = "建议立即执行自动优化。"
            items.append({
                "metric": c["label"],
                "score": c["score"],
                "status": status,
                "cause": cause,
                "suggestion": suggestion,
            })
        weak = min(comps.items(), key=lambda kv: kv[1]["score"])
        summary = (
            f"当前综合性能评分 {score['total']}（{score['grade']} 级）。"
            f"最薄弱的环节是「{weak[1]['label']}」（{weak[1]['score']} 分），"
            f"建议优先处理。整体 Web 层与缓存层表现优秀，数据库与 PHP 运行时存在优化空间。"
        )
        return {"summary": summary, "items": items}

