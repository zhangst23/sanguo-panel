    def _apply_optimization(self, action: str) -> Dict[str, Any]:
        s = self.state
        if action == "worker_scale":
            s["worker_total"] = min(20, s["worker_total"] + 4)
            s["worker_conns"] = 1200
            s["p95_ms"] = _clamp(s["p95_ms"] * 0.85, 80, 1500)
        elif action == "opcache_up":
            s["opcache_total_mb"] = 256.0
            s["php_avg_ms"] = _clamp(s["php_avg_ms"] * 0.8, 10, 600)
        elif action == "cache_warm":
            s["cache_hit"] = _clamp(99.2, 0, 100)
            s["redis_hit"] = _clamp(max(s["redis_hit"], 98), 0, 100)
        elif action == "db_index":
            s["db_avg_ms"] = _clamp(s["db_avg_ms"] * 0.6, 4, 200)
            s["db_qps"] = _clamp(s["db_qps"] * 0.9, 20, 900)
        elif action == "heartbeat_tune":
            s["php_avg_ms"] = _clamp(s["php_avg_ms"] * 0.92, 10, 600)
        else:
            return {"ok": False, "message": f"未知优化项: {action}"}
        self.applied_optimizations[action] = _now()
        self._add_event()
        return {
            "ok": True,
            "action": action,
            "message": "已应用优化，指标正在收敛。",
            "applied_at": _now(),
            "score": self._score(),
        }


